/**
 * Writes tokens.css from src/colors.ts and src/scales.ts, so CSS consumers
 * (the website's globals.css) read the same palette crayola reads in TS.
 *
 * Run with `npm run tokens -w @links/brand` after changing a color. The
 * output is committed: the site build does not depend on running this.
 */
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { colors } from "../src/colors.ts";
import { toCss, toHex } from "../src/oklch.ts";
import { SCALE_NAMES, tokenName } from "../src/scale-types.ts";
import { SCALES } from "../src/scales.ts";

/** `sunDark` → `--sun-dark`. */
const varName = (key: string): string =>
  `--${key.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`)}`;

/** Written by hand below; no alias may take these. */
const ROLES = ["--background", "--foreground"];

const steps = SCALE_NAMES.flatMap((name) =>
  SCALES[name].map((s) => ({ name: `--${tokenName(name, s.step)}`, color: s })),
);

/**
 * Semantic aliases: `--sun: var(--sun-500)`. An alias may replace a legacy
 * colors.ts token of the same name only when the color is identical; any other
 * clash stops the script.
 */
const aliases = steps
  .filter((s) => s.color.name !== "")
  .map((s) => ({ alias: `--${s.color.name}`, target: s.name, hex: toHex(s.color) }));

const replaced = new Set<string>();
for (const { alias, target, hex } of aliases) {
  if (ROLES.includes(alias) || steps.some((s) => s.name === alias)) {
    throw new Error(`${alias} (for ${target}) clashes with a token of the same name.`);
  }
  const legacy = Object.entries(colors).find(([key]) => varName(key) === alias);
  if (legacy) {
    if (legacy[1] !== hex) {
      throw new Error(`${alias} (for ${target}, ${hex}) would change legacy ${alias}: ${legacy[1]}.`);
    }
    replaced.add(alias);
  }
}

const lines = Object.entries(colors)
  .filter(([key]) => !replaced.has(varName(key)))
  .map(([key, value]) => `  ${varName(key)}: ${value};`);
const hexLines = steps.map((s) => `  ${s.name}: ${toHex(s.color)};`);
const p3Lines = steps.map((s) => `    ${s.name}: ${toCss(s.color)};`);
const aliasLines = aliases.map((a) => `  ${a.alias}: var(${a.target});`);

const css = `/*
 * GENERATED by packages/brand/scripts/gen-tokens.ts — do not edit by hand.
 * The sources are packages/brand/src/colors.ts and src/scales.ts.
 *
 * --background and --foreground are the semantic roles: what an interface
 * uses for "the page" and "the text" without picking a brand name.
 *
 * Scales (--sun-100 … --ink-900) are authored in OKLCH. Every screen gets the
 * sRGB hex; wide-gamut screens get the oklch() value, clamped to Display P3.
 * The semantic names point at scale steps, so they follow both.
 */
:root {
  --background: #ffffff;
${lines.join("\n")}
  --foreground: var(--brand-black);

${hexLines.join("\n")}

  /* Semantic names (the name field in src/scales.ts). */
${aliasLines.join("\n")}
}

@media (color-gamut: p3) {
  :root {
${p3Lines.join("\n")}
  }
}
`;

const out = fileURLToPath(new URL("../tokens.css", import.meta.url));
writeFileSync(out, css, "utf8");
console.log(
  `tokens.css written: ${lines.length} colors, ${steps.length} scale steps, ${aliases.length} names` +
    (replaced.size > 0 ? ` (${[...replaced].join(", ")} now an alias).` : "."),
);
